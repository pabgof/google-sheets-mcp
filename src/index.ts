const CONFIG_DIR = join(homedir(), ".config", "mcp-google-sheets");
const TOKEN_PATH = join(CONFIG_DIR, "tokens.json");

const CLIENT_ID = process.env.GOOGLE_CLIENT_ID || "";
const CLIENT_SECRET = process.env.GOOGLE_CLIENT_SECRET || "";

const oauth2Client = new google.auth.OAuth2(CLIENT_ID, CLIENT_SECRET, "http://localhost:3456/callback");

let sheetsApi: sheets_v4.Sheets;
let driveApi: ReturnType<typeof google.drive>;

async function ensureAuth() {
  if (sheetsApi) return;

  if (!existsSync(TOKEN_PATH)) {
    throw new Error(
      "Non authentifie. Lancez d'abord: cd " +
        join(homedir(), "Downloads/mcp-servers/google-sheets") +
        " && npm run auth"
    );
  }

  const tokens = JSON.parse(await readFile(TOKEN_PATH, "utf-8"));
  oauth2Client.setCredentials(tokens);

  // Auto-refresh
  oauth2Client.on("tokens", async (newTokens) => {
    const existing = JSON.parse(await readFile(TOKEN_PATH, "utf-8"));
    const merged = { ...existing, ...newTokens };
    const { writeFile: wf } = await import("fs/promises");
    await wf(TOKEN_PATH, JSON.stringify(merged, null, 2));
  });

  sheetsApi = google.sheets({ version: "v4", auth: oauth2Client });
  driveApi = google.drive({ version: "v3", auth: oauth2Client });
}

